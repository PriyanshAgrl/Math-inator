#ifndef ARITHMETIC_H
#define ARITHMETIC_H

double add(double x, double y);      // Adds two numbers and returns the result
double subtract(double x, double y); // Subtracts y from x and returns the result
double product(double x, double y);  // Multiplies two numbers and returns the result
double divide(double x, double y);   // Divides x by y and returns the result
double rem(double x, double y);             // Calculates the remainder of x divided by y
double sqroot(double x);            // Computes the square root of x
double power(double x, double y);    // Raises x to the power of y
double fact(double x);                   // Calculates the factorial of x
double logarithm(double x, double b);   // Log of (x) to the base b

#endif